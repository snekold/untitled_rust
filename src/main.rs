mod lesson;

// Импортируем нужные инструменты из стандартной библиотеки и нашего нового крейта rand
use rand::Rng;
use std::io;

fn main() {
    println!("🎮 Угадай число!");

    // Генерируем случайное число от 1 до 100
    let secret_number = rand::thread_rng().gen_range(1..=100);
    println!("🤫 Я загадал число от 1 до 100. Попробуй угадать!");

    // Создаем пустую строку, куда пользователь введет свой ответ
    // `mut` означает, что мы будем изменять (mutate) эту переменную
    let mut guess = String::new();

    println!("Введи свое предположение:");

    // Читаем то, что пользователь введет с клавиатуры, и сохраняем в guess
    io::stdin()
        .read_line(&mut guess)
        .expect("Не удалось прочитать строку");

    // Выводим то, что ввел пользователь
    println!("Ты ввел: {}", guess);

    // Пока просто выведем загаданное число, чтобы нам было легче тестировать
    println!("Загаданное число было: {}", secret_number);

    println!("Нажмите Enter, чтобы выйти...");
    let mut _pause = String::new();
    io::stdin()
        .read_line(&mut _pause)
        .expect("Не удалось прочитать");
}
